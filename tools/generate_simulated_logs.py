def ts(day, hms):
    """day = (month, day) in 2026; hms = 'HH:MM:SS' -> ISO string in IST."""
    h, m, s = (int(x) for x in hms.split(":"))
    return datetime(2026, day[0], day[1], h, m, s, tzinfo=IST)


def iso(dt):
    return dt.isoformat()



def write_csv(name, header, rows):
    rows.sort(key=lambda r: r[0])
    with open(OUT / name, "w", newline="") as f:
        w = csv.writer(f, lineterminator="\n")
        w.writerow(header)
        w.writerows(rows)
    print(f"wrote {OUT / name}: {len(rows)} rows")


